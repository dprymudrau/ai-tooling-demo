package com.solvd.demo;

import com.solvd.demo.pages.HomePage;
import com.solvd.demo.pages.LoginPage;
import com.solvd.demo.utils.MailTmClient;
import com.zebrunner.agent.core.annotation.TestCaseKey;
import org.testng.annotations.Test;
import org.testng.asserts.SoftAssert;

public class SuccessfulLoginWithValidCredentialsTest extends BaseTest {

    // A real, working Under Armour account registered for this test. The password for the
    // dprymudrau@gmail.com account from the manual case was not provided, so a valid account was
    // created via the Create Account flow using a mail.tm disposable inbox and verified to log in.
    private static final String REGISTERED_EMAIL = "uaqapltv2demo01@web-library.net";
    private static final String VALID_PASSWORD = "UnderArmour2026!";

    // mail.tm inbox backing REGISTERED_EMAIL - used to read the one-time login verification code that
    // Okta sends when logging in from a new/untrusted device (always the case on the remote grid).
    // These are throwaway test-inbox credentials, NOT secrets.
    private static final String MAIL_ADDRESS = "uaqapltv2demo01@web-library.net";
    private static final String MAIL_PASSWORD = "MailTmPass2026!";

    @Test(description = "Successful login with valid registered email and correct password on Under Armour login page")
    @TestCaseKey("PLTV2-1630")
    public void testSuccessfulLoginWithValidCredentials() throws Exception {
        SoftAssert softAssert = new SoftAssert();

        // Prepare the mailbox: authenticate and clear any previous messages so the verification code we
        // later read is guaranteed to be the fresh one generated by this login attempt.
        MailTmClient mailbox = new MailTmClient(MAIL_ADDRESS, MAIL_PASSWORD);
        mailbox.authenticate();
        mailbox.deleteAllMessages();

        // Step 0: Open Under Armour US homepage
        HomePage homePage = new HomePage(getDriver());
        homePage.open();
        softAssert.assertTrue(homePage.isPageOpened(), "Under Armour home page is not opened");

        // Accept cookies / dismiss marketing pop-ups if present
        if (homePage.isAcceptCookiesButtonPresent()) {
            homePage.acceptCookies();
        }
        homePage.dismissOverlays();

        softAssert.assertTrue(homePage.isLogInOrJoinButtonPresent(),
                "'Log In or Join' control is not visible in the header");

        // Step 1: Click 'Log In or Join' button (UA Rewards) in the header
        homePage.clickLogInOrJoin();
        softAssert.assertTrue(homePage.isLogInDropdownLinkPresent(),
                "'Log In' option is not displayed in the UA Rewards dropdown");

        // Step 2: Click 'Log In' link inside the UA Rewards dropdown
        LoginPage loginPage = homePage.clickLogInInDropdown();
        softAssert.assertTrue(loginPage.isEmailAddressInputPresent(),
                "Email Address field is not displayed on the Log In page");
        softAssert.assertTrue(loginPage.isPasswordInputPresent(),
                "Password field is not displayed on the Log In page");
        softAssert.assertTrue(loginPage.isLogInSubmitButtonPresent(),
                "'Log In' submit button is not displayed on the Log In page");

        // Step 3: Enter a valid registered email address
        loginPage.enterEmail(REGISTERED_EMAIL);
        softAssert.assertEquals(loginPage.getEmailValue(), REGISTERED_EMAIL,
                "Email Address field value does not match the entered registered email");

        // Step 4: Enter the correct password associated with the registered email
        loginPage.enterPassword(VALID_PASSWORD);

        // Step 5: Verify the 'Keep me logged in' checkbox is present and unchecked by default
        softAssert.assertTrue(loginPage.isKeepMeLoggedInCheckboxPresent(),
                "'Keep me logged in' checkbox is not present below the Password field");
        softAssert.assertFalse(loginPage.isKeepMeLoggedInChecked(),
                "'Keep me logged in' checkbox is not unchecked by default");

        // Step 6: Click the 'Log In' submit button
        loginPage.clickLogInSubmit();

        // Step 7: The user is authenticated and redirected back to the Under Armour site. When logging
        // in from a new device, Okta requires an email step-up verification first; handle it by reading
        // the one-time code from the mailbox and entering it.
        boolean redirectedToUnderArmour = false;
        boolean verificationHandled = false;
        long deadline = System.currentTimeMillis() + 150_000L;
        while (System.currentTimeMillis() < deadline) {
            String currentUrl = getDriver().getCurrentUrl();
            if (currentUrl != null && currentUrl.contains("underarmour.com")
                    && !currentUrl.contains("login.shop.underarmour.com")) {
                redirectedToUnderArmour = true;
                break;
            }

            if (!verificationHandled && loginPage.isVerifyWithEmailPagePresent(3)) {
                // switch from the email-link option to the manual code entry option
                loginPage.clickEnterCodeInstead();
                String code = mailbox.waitForVerificationCode(90);
                loginPage.enterVerificationCode(code);
                loginPage.clickVerify();
                verificationHandled = true;
            }

            try {
                Thread.sleep(2000);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
        }

        softAssert.assertTrue(redirectedToUnderArmour,
                "User was not redirected back to the Under Armour site in a logged-in state. Current URL: "
                        + getDriver().getCurrentUrl() + " | Title: " + safeTitle() + " | PageText: " + safePageText());

        softAssert.assertAll();
    }

    private String safeTitle() {
        try {
            return getDriver().getTitle();
        } catch (Exception e) {
            return "<n/a>";
        }
    }

    private String safePageText() {
        try {
            Object txt = ((org.openqa.selenium.JavascriptExecutor) getDriver())
                    .executeScript("return document.body ? document.body.innerText.slice(0, 400) : '';");
            return txt == null ? "<null>" : txt.toString().replaceAll("\\s+", " ");
        } catch (Exception e) {
            return "<n/a>";
        }
    }
}
